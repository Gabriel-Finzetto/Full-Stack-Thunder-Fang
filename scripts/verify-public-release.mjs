const transport = (input, init = {}) => {
  const headers = new Headers(init.headers);
  const key = headers.get('apikey');
  if (/^sb_(secret|publishable)_/.test(key ?? '') && headers.get('authorization') === `Bearer ${key}`) headers.delete('authorization');
  const signal = init.signal ? AbortSignal.any([init.signal, AbortSignal.timeout(30_000)]) : AbortSignal.timeout(30_000);
  return fetch(input, { ...init, headers, signal, cache: 'no-store', redirect: 'error' });
};
